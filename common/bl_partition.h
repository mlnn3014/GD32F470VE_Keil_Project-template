#ifndef BL_PARTITION_H
#define BL_PARTITION_H

#include <stdint.h>

#define BL_FLASH_BASE_ADDR  0x08000000UL // 片内 Flash 起始
#define BL_FLASH_SIZE       0x00080000UL // 512K
#define BL_FLASH_END_ADDR   (BL_FLASH_BASE_ADDR + BL_FLASH_SIZE - 1UL)
#define BL_FLASH_PAGE_SIZE  0x00001000UL // 4K 一页

#define BL_BOOT_START_ADDR  0x08000000UL // BootLoader 区
#define BL_BOOT_SIZE        0x00010000UL
#define BL_BOOT_END_ADDR    (BL_BOOT_START_ADDR + BL_BOOT_SIZE - 1UL)

#define BL_PARAM_START_ADDR 0x08010000UL // Boot 参数区
#define BL_PARAM_SIZE       0x00001000UL
#define BL_PARAM_END_ADDR   (BL_PARAM_START_ADDR + BL_PARAM_SIZE - 1UL)

#define BL_APP1_START_ADDR  0x08011000UL // 正常 APP 区
#define BL_APP1_SIZE        0x00020000UL
#define BL_APP1_END_ADDR    (BL_APP1_START_ADDR + BL_APP1_SIZE - 1UL)

#define BL_APP2_START_ADDR  0x08031000UL // APP 备份区
#define BL_APP2_SIZE        0x00020000UL
#define BL_APP2_END_ADDR    (BL_APP2_START_ADDR + BL_APP2_SIZE - 1UL)

#define BL_TEMP_START_ADDR  0x08051000UL // 固件暂存区
#define BL_TEMP_SIZE        0x00020000UL
#define BL_TEMP_END_ADDR    (BL_TEMP_START_ADDR + BL_TEMP_SIZE - 1UL)

#define BL_DATA_START_ADDR  0x08071000UL // 后面空间预留
#define BL_DATA_SIZE        0x0000F000UL
#define BL_DATA_END_ADDR    (BL_DATA_START_ADDR + BL_DATA_SIZE - 1UL)

#endif
